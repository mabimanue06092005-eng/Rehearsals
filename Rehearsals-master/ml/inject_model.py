"""
Injects the trained turn-classifier model + inference code into index.html,
right before classifyUserTurn(). Idempotent: if the marker block already
exists, it's replaced in place (safe to re-run after retraining).
"""
import json
import os

ROOT = os.path.join(os.path.dirname(__file__), "..")
INDEX_PATH = os.path.join(ROOT, "index.html")
MODEL_PATH = os.path.join(os.path.dirname(__file__), "data", "model.json")

START_MARKER = "// -- BEGIN local turn classifier (generated by ml/inject_model.py) --"
END_MARKER = "// -- END local turn classifier --"
ANCHOR = "async function classifyUserTurn() {"

with open(MODEL_PATH, encoding="utf-8") as f:
    model = json.load(f)
compact_model_json = json.dumps(model, separators=(",", ":"))

# Plain string, NOT an f-string - every brace below is literal JS, no escaping needed.
# __MODEL_JSON__ and the two __COMMENT_*__ placeholders are substituted afterward.
TEMPLATE = """
START_MARKER_PLACEHOLDER
// Trained offline on synthetic Groq-generated examples (ml/generate_data.py,
// ml/train.py) - a TF-IDF + multinomial logistic regression classifier that
// runs entirely client-side: no network call, no latency, no per-turn API
// cost. __COMMENT_ACCURACY__
// It's text-only for now; prosody is fused in via a documented rule below,
// not jointly trained - that becomes a real joint model once real pilot
// session data (Phase 4) is available to retrain on.
const TURN_CLASSIFIER_MODEL = __MODEL_JSON__;

function tfidfVectorizeLocal(text, model) {
  const tokens = (text.toLowerCase().match(/\\b\\w{2,}\\b/g) || []);
  const grams = tokens.slice();
  for (let i = 0; i < tokens.length - 1; i++) grams.push(tokens[i] + ' ' + tokens[i + 1]);
  const counts = {};
  for (const g of grams) {
    if (g in model.vocab) counts[g] = (counts[g] || 0) + 1;
  }
  const vec = {};
  let normSq = 0;
  for (const g in counts) {
    const idx = model.vocab[g];
    const val = counts[g] * model.idf[idx];
    vec[idx] = val;
    normSq += val * val;
  }
  const norm = Math.sqrt(normSq) || 1;
  for (const idx in vec) vec[idx] /= norm;
  return vec;
}

function classifyTextLocally(text) {
  const model = TURN_CLASSIFIER_MODEL;
  const vec = tfidfVectorizeLocal(text, model);
  const logits = model.labels.map((_, ci) => {
    let sum = model.intercept[ci];
    for (const idx in vec) sum += model.coef[ci][idx] * vec[idx];
    return sum;
  });
  const maxLogit = Math.max(...logits);
  const exps = logits.map(l => Math.exp(l - maxLogit));
  const sumExp = exps.reduce((a, b) => a + b, 0);
  const probs = exps.map(e => e / sumExp);
  let bestI = 0;
  for (let i = 1; i < probs.length; i++) if (probs[i] > probs[bestI]) bestI = i;
  return { state: model.labels[bestI], probs, labels: model.labels };
}

// Rule-based fusion, not jointly trained (see note above): only steps in
// when the text signal is genuinely ambiguous, using the same pauseRatio/
// avgVolume/volatility thresholds already used for the delivery label in
// stopProsodyCapture() below, so the two stay consistent with each other.
function applyProsodyAdjustment(textResult, prosody) {
  if (!prosody) return textResult.state;
  const sorted = [...textResult.probs].sort((a, b) => b - a);
  const margin = sorted[0] - sorted[1];
  if (margin > 0.25) return textResult.state;

  const pauseRatio = prosody.pauseRatio, avgVolume = prosody.avgVolume, volatility = prosody.volatility;
  const hesitantSignal = pauseRatio > 0.45 || (volatility > 0.05 && avgVolume < 0.08) || avgVolume < 0.05;
  const confidentSignal = pauseRatio < 0.15 && avgVolume > 0.1;

  if (hesitantSignal && (textResult.state === 'comfortable' || textResult.state === 'defensive')) return 'hesitant';
  if (confidentSignal && textResult.state === 'hesitant') return 'comfortable';
  return textResult.state;
}

// Live coaching nudges are now template-based instead of LLM-generated -
// keeps the whole live-classification loop free and instant. The richer,
// narrative feedback still comes from the real LLM call in the end-of-
// session debrief, which is where that depth actually belongs.
const NUDGE_TEMPLATES = {
  hesitant: [
    "Drop the qualifier - just say what you need directly.",
    "You don't need to apologize before asking for this.",
    "Try that again without the 'maybe' or 'I guess.'",
    "State it as a fact, not a question."
  ],
  defensive: [
    "Try responding to their point instead of defending yours.",
    "Notice the urge to counter-attack - come back to your actual ask.",
    "This is a good moment to pause instead of pushing back."
  ],
  shutdown: [
    "This is the moment to re-engage, not check out.",
    "Try naming what you're feeling instead of going quiet.",
    "Don't let this end in 'whatever' - say what you actually meant."
  ]
};
const NUDGE_CHANCE = 0.35; // most turns should NOT get a nudge

function maybeGetNudge(state) {
  const pool = NUDGE_TEMPLATES[state];
  if (!pool || Math.random() > NUDGE_CHANCE) return null;
  return pool[Math.floor(Math.random() * pool.length)];
}

function classifyUserTurn(text, prosody) {
  const textResult = classifyTextLocally(text);
  const finalState = applyProsodyAdjustment(textResult, prosody);
  return { state: finalState, nudge: maybeGetNudge(finalState) };
}
END_MARKER_PLACEHOLDER

"""

block = (
    TEMPLATE
    .replace("START_MARKER_PLACEHOLDER", START_MARKER)
    .replace("END_MARKER_PLACEHOLDER", END_MARKER)
    .replace("__COMMENT_ACCURACY__", f"Held-out accuracy: {model['meta']['accuracy']*100:.1f}% on {model['meta']['trainedOn']} synthetic examples (see ml/data/eval_report.txt).")
    .replace("__MODEL_JSON__", compact_model_json)
    .strip("\n")
)

with open(INDEX_PATH, encoding="utf-8") as f:
    html = f.read()

if START_MARKER in html:
    start = html.index(START_MARKER)
    end = html.index(END_MARKER) + len(END_MARKER)
    html = html[:start] + block + "\n\n" + html[end:].lstrip("\n")
else:
    assert ANCHOR in html, "anchor function not found - has classifyUserTurn already been edited?"
    html = html.replace(ANCHOR, block + "\n\n" + ANCHOR, 1)

with open(INDEX_PATH, "w", encoding="utf-8") as f:
    f.write(html)

print(f"Injected model ({len(compact_model_json)/1024:.1f} KB) into {INDEX_PATH}")
